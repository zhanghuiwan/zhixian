import { describe, expect, it } from 'vitest';
import { actionLabel, planAIAction } from './ai-actions';
import type { AIResponseAction } from './types';

const action = (type: AIResponseAction['type'], payload: Record<string, unknown>): AIResponseAction => ({ id: 'test', type, label: '执行', payload });

describe('AI response actions', () => {
  it('turns a collection action into a validated API request', () => {
    expect(planAIAction(action('add_word_to_collection', { term: 'serene', collection_id: 8 }))).toEqual({
      kind: 'request', path: '/library/personal/8/words', body: { terms: ['serene'] }, successMessage: 'serene 已加入词书', invalidate: ['library', 'vocabulary'],
    });
  });

  it('rejects incomplete write actions instead of pretending they succeeded', () => {
    expect(() => planAIAction(action('save_sentence', { translation: '译文' }))).toThrow('缺少句子内容');
  });

  it('labels an incomplete custom-word action as navigation', () => {
    const value = action('request_custom_word', { term: 'unlisted' });
    expect(actionLabel(value)).toBe('前往添加单词');
    expect(planAIAction(value)).toEqual({ kind: 'navigate', destination: 'vocabulary', term: 'unlisted' });
  });

  it('opens an article generated by the backend at its mobile route', () => {
    expect(planAIAction(action('navigate', { path: '/articles/42' }))).toEqual({ kind: 'navigate', destination: 'article', id: 42 });
  });
});
